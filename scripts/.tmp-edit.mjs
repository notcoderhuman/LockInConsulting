import fs from 'node:fs'
const rep = (s, x, y) => {
  if (!s.includes(x)) throw new Error('missing ' + x.slice(0, 70))
  return s.split(x).join(y)
}
let c = fs.readFileSync('lib/derek/completeness.ts', 'utf8').split('\n')
const i = c.findIndex((l) => l.startsWith('const SCORE'))
if (i < 0) throw new Error('SCORE line')
c.splice(i, 1, ...fs.readFileSync('scripts/.tmp-score.txt', 'utf8').trim().split('\n'))
let cs = c.join('\n')
cs = rep(cs, "      const value = Number(m[2])\n      if (Number.isFinite(value))", "      const value = Number(m[2])\n      // 0 is a table filler (\"no requirement\"), not a required score.\n      if (Number.isFinite(value) && value > 0)")
fs.writeFileSync('lib/derek/completeness.ts', cs)
let g = fs.readFileSync('lib/derek/providers/gemini.ts', 'utf8')
g = rep(g, "  let uncertain = false\n  if (text.startsWith(UNCERTAIN_MARKER)) {", "  let uncertain = false\n  // The marker may sit anywhere (the model sometimes opens a later paragraph with it): it is removed wherever it is and still means \"uncertain\".\n  if (text.includes(UNCERTAIN_MARKER) && !text.startsWith(UNCERTAIN_MARKER)) {\n    uncertain = true\n    text = text.split(UNCERTAIN_MARKER).join('').replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').replace(/ {2,}/g, ' ').trim()\n    if (!text) throw new ProviderError('invalid_response', true)\n  }\n  if (text.startsWith(UNCERTAIN_MARKER)) {")
fs.writeFileSync('lib/derek/providers/gemini.ts', g)
let p = fs.readFileSync('lib/derek/provider.ts', 'utf8')
p = rep(p, "Close with one concrete next step.',", "Include the application fee and any minimum grade or score the pages state. Close with one concrete next step.',")
fs.writeFileSync('lib/derek/provider.ts', p)
let d = fs.readFileSync('lib/derek/drafts.ts', 'utf8')
d = rep(d, "The earlier instruction to avoid figures does not apply to figures stated in EVIDENCE.", "Keep the whole comparison under about 1,800 characters. The earlier instruction to avoid figures does not apply to figures stated in EVIDENCE.")
fs.writeFileSync('lib/derek/drafts.ts', d)
