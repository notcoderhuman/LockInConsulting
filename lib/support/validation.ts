import { z } from 'zod'

// Server-side validation for everything a student or team member types into the chat.
// Text is stored as plain text and rendered by React as text (never as HTML), so validation is
// about size, encoding and invisible characters rather than markup.

export const MESSAGE_MAX = 4000
export const SUBJECT_MAX = 160

// C0/C1 controls except tab and newline, plus bidi overrides and zero-width characters that can
// disguise text in the inbox.
const INVISIBLE = /[\u0000-\u0008\u000B-\u001F\u007F-\u009F​-‏‪-‮⁦-⁩﻿]/g

export function normaliseText(raw: string): string {
  return raw
    .normalize('NFC')
    .replace(/\r\n?/g, '\n')
    .replace(INVISIBLE, '')
    .replace(/\n{4,}/g, '\n\n\n')
    .trim()
}

const text = (max: number, label: string) =>
  z
    .string({ error: `${label} is required.` })
    .transform(normaliseText)
    .pipe(z.string().min(1, `${label} cannot be empty.`).max(max, `${label} must be at most ${max} characters.`))

export const messageBody = text(MESSAGE_MAX, 'Message')

/** Idempotency key generated by the sender for each distinct send (UUID or similar). */
export const clientRequestId = z.string().regex(/^[A-Za-z0-9-]{8,64}$/, 'Invalid request id.')

export const newConversationInput = z.object({
  subject: z.union([text(SUBJECT_MAX, 'Subject'), z.literal(''), z.undefined()]).optional(),
  body: messageBody,
  clientRequestId,
})

export const newMessageInput = z.object({ body: messageBody, clientRequestId })

export const reasonText = text(500, 'Reason')

/** Subject defaults to the first line of the question. */
export function deriveSubject(subject: string | undefined, body: string): string {
  const s = subject?.trim() || body.split('\n')[0]
  return s.length > SUBJECT_MAX ? `${s.slice(0, SUBJECT_MAX - 1)}…` : s
}

export const PAGE_SIZE_MAX = 50

export function parsePageParams(url: URL): { before: number | null; limit: number } {
  const before = Number(url.searchParams.get('before'))
  const limit = Number(url.searchParams.get('limit'))
  return {
    before: Number.isSafeInteger(before) && before > 0 ? before : null,
    limit: Number.isSafeInteger(limit) && limit > 0 ? Math.min(limit, PAGE_SIZE_MAX) : 30,
  }
}

/** Notification targets are same-site paths only (mirrors ck_notifications_target). */
export function isSafeTargetPath(path: string): boolean {
  return /^\/(?!\/)[A-Za-z0-9\-._~/?=&%#]*$/.test(path) && !path.includes('\\') && path.length <= 300
}
